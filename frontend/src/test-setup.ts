import '@testing-library/jest-dom'

// jsdom doesn't implement matchMedia — stub it globally so any component
// calling useMediaQuery doesn't throw in the test environment.
Object.defineProperty(window, 'matchMedia', {
  writable: true,
  value: (query: string) => ({
    matches: false,
    media: query,
    onchange: null,
    addListener: () => {},
    removeListener: () => {},
    addEventListener: () => {},
    removeEventListener: () => {},
    dispatchEvent: () => false,
  }),
})
